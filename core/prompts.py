ONLY_QUESTION = " Не добавляй факты и пункты сверх вопроса и тех, что есть во фрагментах."


def plan_hint(plan, short_refs: list[str]) -> str:
    """Подсказка по сценарию плана; пусто для fact. Пустые части опускаются."""
    s = plan.scenario
    if s == "false_premise":
        text = "Проверь утверждения пользователя"
        if plan.claims:
            text += ": «" + "»; «".join(plan.claims) + "»"
        return (text + ". Если фрагменты им противоречат — status false_premise, начни с «Нет», "
                "дай верное значение со ссылкой." + ONLY_QUESTION)
    if s == "date_edition":
        text = "Дата события: " + (f"{plan.event_date:%d.%m.%Y}" if plan.event_date else "см. вопрос")
        return (text + ". Отвечай по редакции с пометкой «действовала на дату события»; "
                "если сейчас значение другое — назови его одной фразой.")
    if s == "multi_doc":
        text = "Вопрос касается нескольких документов"
        if short_refs:
            text += ": " + ", ".join(short_refs)
        return (text + ". Ответь по каждому со ссылкой на пункт. Если в вопросе нет даты, "
                "используй только действующую редакцию регламента." + ONLY_QUESTION)
    if s == "not_in_kb":
        return ("Возможно, нужной нормы в базе нет. Если ответа во фрагментах нет — status insufficient: "
                "скажи, каких сведений не хватает, без номеров статей, которых нет во фрагментах." + ONLY_QUESTION)
    if s == "illegal":
        return ("Запрос противоправный: не помогай (status refuse_illegal). Коротко объясни требования "
                "закона и ответственность по фрагментам, со ссылками." + ONLY_QUESTION)
    if s == "old_law":
        return ("В базе только действующая редакция закона: скажи, что прежней нет, "
                "и назови действующее значение со ссылкой." + ONLY_QUESTION)
    if s == "offtopic":
        return "status offtopic, одна-две фразы."
    return ""
