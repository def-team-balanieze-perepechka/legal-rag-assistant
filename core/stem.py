from __future__ import annotations

import re

_TOKEN_RE = re.compile(r"[а-яa-z0-9]+(?:[.,/-][0-9]+)*")

_ENDINGS = sorted(
    """
    иями ями ами ием ием ьми ого его ому ему ыми ими ой ей ий ый ая яя ое ее ые ие ую юю ым им ом ем
    ах ях ов ев ей ам ям ия ья ию ью ии ие ья ье ью ия ть ти ся сь ет ют ут ит ат ят ал ил ыл ла ли
    ло ен ан ын ость ости остью ование ования ованию ованием ировать ировал ений ения ению ением
    а я о е и ы у ю ь й
    """.split(),
    key=len,
    reverse=True,
)

STOPWORDS = frozenset(
    """
    и в во не что он на я с со как а то все она так его но да ты к у же вы за бы по только ее мне
    было вот от меня еще нет о из ему теперь когда даже ну вдруг ли если уже или ни быть был него
    до вас нибудь опять уж вам ведь там потом себя ничего ей может они тут где есть надо ней для мы
    тебя их чем была сам чтоб без будто чего раз тоже себе под будет ж тогда кто этот того потому
    этого какой совсем ним здесь этом один почти мой тем чтобы нее сейчас были куда зачем всех
    никогда можно при наконец два об другой хоть после над больше тот через эти нас про всего них
    какая много разве три эту моя впрочем хорошо свою этой перед иногда лучше чуть том нельзя такой
    им более всегда конечно всю между это также который которые которых
    """.split()
)


def normalize(text: str) -> str:
    return text.lower().replace("ё", "е")


def stem(word: str) -> str:
    if len(word) <= 4 or not ("а" <= word[0] <= "я"):
        return word
    for end in _ENDINGS:
        if word.endswith(end) and len(word) - len(end) >= 3:
            return word[: -len(end)]
    return word


def tokenize(text: str) -> list[str]:
    """Токены для BM25: нижний регистр, ё->е, без стоп-слов, со стеммингом."""
    return [stem(t) for t in _TOKEN_RE.findall(normalize(text)) if t not in STOPWORDS]
